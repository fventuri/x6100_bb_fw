/*
 * i2s_rx_path -- X6100 (STM32F427) receive-path integration (M3).
 * ============================================================================
 * The strong override of i2s.c's weak i2s_dsp() hook. It runs in the
 * DMA1_Stream3 transfer-complete ISR once per completed 128-frame I2S bank and
 * wires the real RX datapath that the M2 spike exercised by direct calls:
 *
 *   i2s_dsp(rx_audio, rx_iq, tx_audio, tx_iq):
 *     1. Drv_Fpga_Codec_PushIqBank(rx_iq)      : codec I/Q bank -> raw ring
 *     2. Sdr_Rx_Process(audio50, 64)           : decimate 100->25k, demod,
 *                                                audio resample -> 64 @ 50 kHz
 *     3. arm_fir_interpolate_f32 (x2 half-band): 64 @ 50 kHz -> 128 @ 100 kHz
 *     4. pack into tx_audio (both channels, Q1.31) -> I2S2ext -> codec DAC
 *
 * Step 3 replaces M2's linear-x2 placeholder with the proper half-band
 * interpolator from Platform/f427/audio_out_interp_filter.h (generated by
 * tools/gen_audio_out_interp.py).
 *
 * Call I2s_Rx_Path_Init() once, after the SDR module initialisers and before
 * i2s_start() arms the ISR.
 */
#pragma once

#include <stdint.h>

/* Initialise the audio-out interpolator state. Call after Sdr_Rx_Init() and
 * before the first bank is serviced (i.e. before i2s_start()). */
void I2s_Rx_Path_Init(void);

/* Per-bank i2s_dsp() cost in CPU cycles (DWT): last bank and running peak. The
 * reader may clear the peak. Zero until DWT->CYCCNT is enabled. */
extern volatile uint32_t g_i2s_dsp_cyc;
extern volatile uint32_t g_i2s_dsp_cyc_max;

/* Linear output volume applied to the demodulated audio before packing. Default
 * 0.1 (-20 dB). Settable at runtime. */
extern volatile float g_rx_volume;
